const DAYS: Record<Lang, { short: string[]; long: string[] }> = {
  en: {
    short: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
    long: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'],
  },
  tr: {
    short: ['Pzt', 'Sal', 'Çar', 'Per', 'Cum', 'Cmt', 'Paz'],
    long: ['Pazartesi', 'Salı', 'Çarşamba', 'Perşembe', 'Cuma', 'Cumartesi', 'Pazar'],
  },
}

const LOCALES: Record<Lang, Locale> = { en: enGB, tr: trLocale }

const KIND_KEYS: Record<SlotKind, { label: Key; lower: Key }> = {
  lecture: { label: 'lecture', lower: 'lectureLower' },
  lab: { label: 'lab', lower: 'labLower' },
  practice: { label: 'practice', lower: 'practiceLower' },
}

const HUE_KEYS: Record<HueKey, Key> = {
  pink: 'huePink',
  orange: 'hueOrange',
  yellow: 'hueYellow',
  cyan: 'hueCyan',
  slate: 'hueSlate',
  green: 'hueGreen',
  violet: 'hueViolet',
}

export function translator(lang: Lang) {
  const dict = lang === 'tr' ? tr : en
  const locale = LOCALES[lang]

  const t = (key: Key, vars?: Record<string, string | number>) =>
    vars ? dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : dict[key]

  /** 90 → "1.5 h" / "1,5 sa" */
  const hours = (minutes: number) => {
    const h = minutes / 60
    const n = Number.isInteger(h) ? String(h) : h.toFixed(1)
    return lang === 'tr' ? `${n.replace('.', ',')} sa` : `${n} h`
  }

  const fmt = (date: Date, pattern: string) => format(date, pattern, { locale })

  /** Due date relative to today, with a tone for coloring. */
  const dueLabel = (due: string, today = new Date()) => {
    const d = parseISO(due)
    const diff = differenceInCalendarDays(d, today)
    if (diff < -1) return { text: t('daysLate', { n: -diff }), tone: 'late' as const }
    if (diff === -1) return { text: t('yesterday'), tone: 'late' as const }
    if (diff === 0) return { text: t('dueToday'), tone: 'soon' as const }
    if (diff === 1) return { text: t('dueTomorrow'), tone: 'soon' as const }
    if (diff < 7) return { text: DAYS[lang].long[(d.getDay() + 6) % 7], tone: 'soon' as const }
    return { text: fmt(d, 'd MMM'), tone: 'later' as const }
  }

  return {
    lang,
    locale,
    t,
    hours,
    fmt,
    dueLabel,
    days: DAYS[lang].short,
    daysLong: DAYS[lang].long,
    kind: (k: SlotKind) => dict[KIND_KEYS[k].label],
    kindLower: (k: SlotKind) => dict[KIND_KEYS[k].lower],
    hueName: (h: HueKey) => dict[HUE_KEYS[h]],
  }
}

export type T = ReturnType<typeof translator>

export function useT() {
  const lang = usePlanner((s) => s.prefs.lang)
  return useMemo(() => translator(lang), [lang])
}
